// See README.md for how these figures were worked out. Every tax amount is
// per line and rounded half-up, e.g. QST on 2450.00 = 244.3875 -> 244.39.

const line = (
  id: string,
  kind: string,
  description: string,
  amount: string,
  taxCode: string,
  taxAmount: string
): InvoiceLine => ({ id, kind, description, amount, taxCode, taxAmount });

const docs = (shipmentId: string, withPod = false): Attachment[] => [
  { id: `${shipmentId}-inv`, kind: "MGC_INVOICE", fileName: `${shipmentId}-invoice.pdf` },
  { id: `${shipmentId}-bol`, kind: "BOL", fileName: `${shipmentId}-BOL.pdf` },
  ...(withPod
    ? [{ id: `${shipmentId}-pod`, kind: "POD" as const, fileName: `${shipmentId}-POD.pdf` }]
    : []),
];

const created = (id: string, at: string): HistoryEntry => ({
  id: `${id}-h1`,
  at,
  user: "Sync",
  action: "Created as draft from MGC shipment",
});

